const CSR_APP_INCLUDE: &str = r#"use leptos::*;
use leptos_router::*;

include!(concat!(env!("OUT_DIR"), "/routes.rs"));

#[component]
pub fn App() -> impl IntoView {
    view! {
        <Router>
            {routes()}
        </Router>
    }
}
"#;

