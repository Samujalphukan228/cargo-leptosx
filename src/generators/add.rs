use crate::generators::{self, set_feature_flag};
use anyhow::{bail, Result};
use std::fs;
use std::path::Path;

pub fn run(feature: &str, force: bool, codegen: bool) -> Result<()> {
    generators::ensure_project()?;
    generators::validate_feature(feature)?;

    let key = generators::toml_key(feature).unwrap();
    if generators::feature_installed(key)? && !force {
        bail!("`{feature}` is already installed — use `--force` to re-run it");
    }

    match feature {
        "tailwind" => add_tailwind()?,
        "router" => generators::add_cargo_dep("leptos_router", "\"0.6\"")?,
        "lucide" => add_lucide()?,
        "ui" => add_ui()?,
        "api" => add_api()?,
        "file-router" => crate::generators::pages_scan::install(codegen)?,
        _ => unreachable!(),
    }

    set_feature_flag(feature, true)?;
    println!("✔ added `{}`", feature);
    Ok(())
}

fn add_tailwind() -> Result<()> {
    if !Path::new("tailwind.config.js").exists() {
        fs::write(
            "tailwind.config.js",
            "/** @type {import('tailwindcss').Config} */\nmodule.exports = {\n  content: [\"./src/**/*.rs\", \"./index.html\"],\n  theme: { extend: {} },\n  plugins: [],\n};\n",
        )?;
    }
    fs::write(
        "style/main.css",
        "@tailwind base;\n@tailwind components;\n@tailwind utilities;\n",
    )?;
    println!("  → style/main.css uses @tailwind directives");
    println!("  → build it with: npx tailwindcss -i style/main.css -o style/output.css --watch");
    Ok(())
}

fn add_lucide() -> Result<()> {
    generators::add_cargo_dep("leptos_icons", "\"0.3\"")?;
    fs::create_dir_all("src/components")?;
    generators::ensure_mod_line("src/components/mod.rs", "pub mod icons;")?;
    fs::write("src/components/icons.rs", ICONS_RS)?;
    Ok(())
}

fn add_ui() -> Result<()> {
    fs::create_dir_all("src/components/ui")?;
    generators::ensure_mod_line("src/components/mod.rs", "pub mod ui;")?;
    if !Path::new("src/components/ui/mod.rs").exists() {
        fs::write("src/components/ui/mod.rs", UI_MOD_RS)?;
    }
    Ok(())
}

fn add_api() -> Result<()> {
    generators::add_cargo_dep("reqwest", r#"{ version = "0.12", features = ["json"] }"#)?;
    generators::add_cargo_dep("serde", r#"{ version = "1", features = ["derive"] }"#)?;
    fs::create_dir_all("src/api")?;
    fs::write("src/api/mod.rs", API_MOD)?;
    generators::ensure_mod_line("src/lib.rs", "pub mod api;")?;
    Ok(())
}

